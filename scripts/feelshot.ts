import { chromium } from "playwright";
(async () => {
  const b = await chromium.launch({ args: ["--use-gl=swiftshader", "--enable-webgl", "--ignore-gpu-blocklist"] });
  const ctx = await b.newContext({ viewport: { width: 1400, height: 860 } });
  await ctx.addInitScript("localStorage.setItem('bo-intro-seen','1');localStorage.setItem('bo-guest','1');localStorage.setItem('bo-name','TESTER')");
  const p = await ctx.newPage();
  const errs: string[] = [];
  p.on("pageerror", (e) => errs.push(String(e)));
  p.on("console", (m) => m.type() === "error" && errs.push(m.text()));
  await p.goto("http://127.0.0.1:5173/");
  await p.getByRole("button", { name: /CREATE A ROOM/ }).click({ timeout: 30000 });
  await p.waitForURL(/\/r\//, { timeout: 60000 });
  await p.locator(".bot-level.len button", { hasText: "1:30" }).click({ timeout: 60000 });
  await p.locator(".bot-level.len button.on", { hasText: "1:30" }).waitFor({ timeout: 20000 });
  console.log("length set to 1:30");
  await p.getByRole("button", { name: "START THE NIGHT" }).click({ timeout: 60000 });
  await p.locator(".hud-clock").waitFor({ timeout: 90000 });
  await p.waitForTimeout(4500);
  console.log("clock:", await p.locator(".hud-clock").innerText());
  await p.mouse.move(700, 300);
  await p.keyboard.down("w");
  await p.keyboard.down("Shift");
  await p.waitForTimeout(2500);
  await p.screenshot({ path: "demo/feel-sprint.png" });
  await p.keyboard.up("Shift");
  await p.mouse.down();
  await p.waitForTimeout(700);
  await p.screenshot({ path: "demo/feel-fire.png" });
  await p.mouse.up();
  await p.keyboard.up("w");
  await p.waitForTimeout(9000);
  await p.screenshot({ path: "demo/feel-later.png" });
  const st = await p.evaluate(() => (document.querySelector(".bar.stamina") as HTMLElement)?.style.opacity);
  console.log("stamina bar opacity", st, "errors", errs.slice(0, 5));
  await b.close();
})();
