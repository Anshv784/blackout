import { chromium } from "playwright";
const out = process.argv[2];
const b = await chromium.launch({ args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
await ctx.addInitScript(() => localStorage.setItem("bo-intro-seen", "1"));
const p = await ctx.newPage();
const errs: string[] = [];
p.on("pageerror", (e) => errs.push(e.message));
const t0 = Date.now();
const log = (...a: unknown[]) => console.log(`[${((Date.now() - t0) / 1000).toFixed(0)}s]`, ...a);
await p.goto("http://127.0.0.1:5173/"); await p.waitForTimeout(6000);
await p.screenshot({ path: `${out}/1-gate.png` }); log("gate");
await p.click("text=PLAY NOW");
await p.waitForSelector(".lobby2, .game", { timeout: 60000 }); await p.waitForTimeout(2500);
await p.screenshot({ path: `${out}/2-lobby.png` }); log("lobby");
await p.waitForSelector(".game", { timeout: 90000 }); await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/3-night.png` }); log("night card");
await p.waitForTimeout(9000);
await p.screenshot({ path: `${out}/4-play.png` }); log("play");
await p.waitForSelector(".reveal", { timeout: 200000 }); log("reveal");
await p.waitForSelector(".verdict", { timeout: 60000 }).catch(() => {}); await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/5-verdict.png` }); log("verdict");
await p.click("text=WATCH THE REPLAY").catch(() => {}); await p.waitForTimeout(2000);
await p.screenshot({ path: `${out}/6-replay.png` });
console.log("errors", errs.slice(0, 8));
await b.close();
