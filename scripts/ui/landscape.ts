// A phone held sideways, start to end: ENTER, the story, the gate, guest card, lobby,
// countdown, a live night (crosshair, controls), map, settings, the volume panel, the verdict.
import { chromium } from "playwright";
(async () => {
  const b = await chromium.launch({ args: ["--use-gl=swiftshader", "--enable-webgl", "--ignore-gpu-blocklist"] });
  const ctx = await b.newContext({ viewport: { width: 780, height: 360 }, hasTouch: true, isMobile: true, deviceScaleFactor: 2 });
  const p = await ctx.newPage();
  const errs: string[] = [];
  p.on("pageerror", (e) => errs.push(String(e)));
  const shot = (n: string) => p.screenshot({ path: `demo/L-${n}.png`, timeout: 120000 });
  await p.goto("http://127.0.0.1:5173/");
  await p.waitForTimeout(2000);
  await shot("01-enter");
  await p.getByRole("button", { name: "ENTER" }).tap();
  await p.locator(".intro-loading").waitFor({ state: "detached", timeout: 90000 });
  await p.waitForTimeout(9000);
  await shot("02-story");
  await p.getByText("skip ›").tap();
  await p.waitForTimeout(3500);
  await shot("03-gate");
  await p.getByRole("button", { name: /CREATE A ROOM/ }).tap();
  await p.waitForTimeout(1000);
  await shot("04-wallet");
  await p.getByRole("button", { name: /PLAY AS GUEST/ }).tap();
  await p.getByRole("button", { name: /ENTER AS GUEST/ }).tap();
  await p.waitForURL(/\/r\//, { timeout: 90000 });
  await p.waitForTimeout(3500);
  await shot("05-lobby");
  await p.getByRole("button", { name: "START THE NIGHT" }).tap({ timeout: 90000 });
  await p.locator(".night-card").waitFor({ timeout: 120000 });
  await shot("06-countdown");
  await p.locator(".night-card").waitFor({ state: "detached", timeout: 90000 });
  await p.waitForTimeout(3000);
  await shot("07-live");
  await p.locator(".game-tools button", { hasText: "MAP" }).tap();
  await p.waitForTimeout(1500);
  await shot("08-map");
  await p.locator(".map-card .menu-x").tap();
  await p.waitForTimeout(600);
  await p.locator(".game-tools button", { hasText: "SETTINGS" }).tap();
  await p.waitForTimeout(1200);
  await shot("09-settings");
  await p.keyboard.press("Escape");
  await p.waitForTimeout(600);
  await p.locator(".game-tools .sound-toggle").tap();
  await p.waitForTimeout(800);
  await shot("10-volume");
  await p.locator(".game-tools .sound-toggle").tap();
  const id = p.url().match(/\/r\/(\d+)/)![1];
  await p.evaluate(`(async () => { const { client } = await import('/src/game/identity.ts'); await client.sendEr([client.endNowIx(${id}n)]); })()`);
  await p.locator(".reveal-top").waitFor({ timeout: 120000 });
  await p.waitForTimeout(6000);
  await shot("11-verdict");
  console.log("errors", errs);
  await b.close();
})();
