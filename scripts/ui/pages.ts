import { chromium } from "playwright";
(async () => {
  const b = await chromium.launch({ args: ["--use-gl=swiftshader", "--enable-webgl", "--ignore-gpu-blocklist"] });
  const p = await b.newPage({ viewport: { width: 1400, height: 900 } });
  const errs: string[] = [];
  p.on("pageerror", (e) => errs.push(String(e)));
  await p.addInitScript("localStorage.setItem('bo-intro-seen','1')");
  await p.goto("http://127.0.0.1:5173/#/board");
  await p.waitForTimeout(7000);
  await p.screenshot({ path: "demo/board.png", fullPage: true });
  await p.goto("http://127.0.0.1:5173/#/how");
  await p.waitForTimeout(2000);
  await p.getByRole("button", { name: "PEEK AT A MATCH" }).click();
  await p.waitForTimeout(12000);
  await p.screenshot({ path: "demo/how.png", fullPage: true });
  await p.setViewportSize({ width: 390, height: 844 });
  await p.waitForTimeout(800);
  await p.screenshot({ path: "demo/how-mobile.png", fullPage: true });
  console.log("errors", errs);
  await b.close();
})();
