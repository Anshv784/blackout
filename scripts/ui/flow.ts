import { chromium } from "playwright";
const out = process.argv[2];
const b = await chromium.launch({ args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
const ctx = await b.newContext({ viewport: { width: 1440, height: 900 } });
await ctx.addInitScript({
  content: `localStorage.setItem("bo-intro-seen","1");
  (function(){ var pk="9Sg12k15Ann4SKSxcA85bq5fbpq7WMLH9bLCTUbTRkQV"; var o={toString:function(){return pk}};
  window.phantom={solana:{isPhantom:true,publicKey:o,connect:async function(){return {publicKey:o}},disconnect:async function(){}}}; })();`,
});
const p = await ctx.newPage();
const errs: string[] = [];
p.on("pageerror", (e) => errs.push(e.message));
const t0 = Date.now();
const log = (...a: unknown[]) => console.log(`[${((Date.now() - t0) / 1000).toFixed(0)}s]`, ...a);
await p.goto("http://127.0.0.1:5173/"); await p.waitForTimeout(6000);
await p.screenshot({ path: `${out}/1-gate.png` }); log("gate");
await p.click("text=CREATE A ROOM");
await p.waitForSelector(".wgate", { timeout: 10000 }); await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/1b-wallet.png` }); log("wallet gate");
await p.click(".wgate-wallet:has-text('Phantom')");
await p.waitForTimeout(3000);
console.log("gate text:", (await p.textContent(".wgate-card"))?.slice(0, 300));
await p.waitForSelector(".wgate-input", { timeout: 15000 }); await p.waitForTimeout(500);
await p.screenshot({ path: `${out}/1c-callsign.png` }); log("callsign");
await p.click("text=ENTER THE YARD");
await p.waitForSelector(".lobby2, .game", { timeout: 60000 }); await p.waitForTimeout(2500);
await p.screenshot({ path: `${out}/2-lobby.png` }); log("lobby");
await p.waitForSelector("button:has-text('START THE NIGHT')", { timeout: 60000 });
await p.click(".stepper button:has-text('−')"); await p.waitForTimeout(2500);
await p.screenshot({ path: `${out}/2b-lobby-5.png` }); log("size 5");
await p.click("button:has-text('START THE NIGHT')");
await p.waitForSelector(".game", { timeout: 90000 }); await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/3-night.png` }); log("night card");
await p.waitForTimeout(9000);
await p.screenshot({ path: `${out}/4-play.png` }); log("play");
await p.waitForSelector(".reveal", { timeout: 200000 }); log("reveal");
await p.waitForSelector(".verdict", { timeout: 60000 }).catch(() => {}); await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/5-verdict.png` }); log("verdict");
await p.click("text=WATCH THE REPLAY").catch(() => {}); await p.waitForTimeout(2000);
await p.screenshot({ path: `${out}/6-replay.png` });
console.log("errors", errs.slice(0, 8));
await b.close();
